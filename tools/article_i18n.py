def slugs():
    return sorted(s for s in os.listdir(ART) if os.path.exists(os.path.join(ART, s, "en.txt")))


def load_meta(slug):
    return json.load(open(os.path.join(ART, slug, "meta.json"), encoding="utf-8"))


def en_alt(slug, d, meta):
    if d.get("alt"):
        return d["alt"]
    from articles import hero_alt  # noqa: E402
    from registry import registry  # noqa: E402
    global _REG
    if _REG is None:
        _REG = registry()
    return hero_alt(meta["hero"], "en", _REG)


_REG = None


def plain_seg(text):
    t = norm(text)
    return (sid(t), t) if translatable(t) else (None, t)


def article_plan(slug):
    """Ordered list of (field, kind, payload) describing how en.txt maps to segments.
    Returns (plan, segs) where segs is an ordered list of (id, English) for translatable segments."""
    meta = load_meta(slug)
    d = parse_txt(os.path.join(ART, slug, "en.txt"))
    plan, segs = {}, []

    def add_plain(field, text):
        i, t = plain_seg(text)
        if i:
            segs.append((i, t))
        return (i, t)

    def add_html(text):
        toks, ss = frag_segments(text)
        for s in ss:
            if s.id:
                segs.append((s.id, s.text))
        return text

    seo = d["seo_title"]
    plan["seo_suffix"] = seo.endswith(SEO_SUFFIX)
    for f in ("title", "dek", "q", "a"):
        plan[f] = add_plain(f, d[f])
    plan["seo_title"] = add_plain("seo_title", seo[: -len(SEO_SUFFIX)] if plan["seo_suffix"] else seo)
    plan["desc"] = add_plain("desc", d["desc"])
    plan["takeaways"] = [add_html(x) for x in d["takeaways"]]
    plan["alt"] = add_plain("alt", en_alt(slug, d, meta))
    plan["body"] = add_html(d["body"])
    for f in ("insight_quote", "insight"):
        plan[f] = add_plain(f, d[f])
    plan["prop_intro"] = add_html(d["prop_intro"])
    plan["prop_items"] = [add_html(x) for x in d["prop_items"]]
    plan["prop_outro"] = add_html(d["prop_outro"])
    plan["faq"] = [(add_plain("faq_q", q), add_html(a)) for q, a in d["faq"]]
    plan["note"] = add_plain("note", d["note"])
    cat_en = UI["en"]["cats"].get(meta.get("cat"))
    plan["section"] = None if d["section"] == cat_en else add_plain("section", d["section"])
    plan["tags"] = [add_plain("tag", t) for t in d["tags"]]
    plan["keywords"] = add_plain("keywords", d["keywords"])
    seen, uniq = set(), []
    for i, t in segs:
        if i not in seen:
            seen.add(i)
            uniq.append((i, t))
    return meta, d, plan, uniq


def load_tm(code):
    p = os.path.join(TM_DIR, code + ".json")
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}


def save_tm(code, tm):
    os.makedirs(TM_DIR, exist_ok=True)
    with open(os.path.join(TM_DIR, code + ".json"), "w", encoding="utf-8") as f:
        json.dump(dict(sorted(tm.items())), f, ensure_ascii=False, indent=0)
        f.write("\n")


def is_original(slug, hl):
    """True if <hl>.txt exists and was written by hand (an original or an imported version)."""
    p = os.path.join(ART, slug, hl + ".txt")
    if not os.path.exists(p):
        return False
    with open(p, encoding="utf-8") as f:
        return not f.readline().startswith("# generated")


def all_plans():
    return [(s,) + article_plan(s) for s in slugs()]


def write_source(plans):
    src = {}
    for slug, meta, d, plan, segs in plans:
        for i, t in segs:
            src[i] = t
    os.makedirs(TM_DIR, exist_ok=True)
    with open(os.path.join(TM_DIR, "source.json"), "w", encoding="utf-8") as f:
        json.dump(dict(sorted(src.items())), f, ensure_ascii=False, indent=0)
        f.write("\n")
    return src


def needed(code, plans):
    """Articles that still need language `code` (no hand-written version) with their segments."""
    hl = CODE2HL[code]
    return [p for p in plans if not is_original(p[0], hl)]


def todo_lines(code, plans):
    tm = load_tm(code)
    seen, out = set(), []
    # newest articles first so a partial translation run publishes the most recent pieces first
    for slug, meta, d, plan, segs in sorted(needed(code, plans), key=lambda p: p[1]["published"], reverse=True):
        for i, t in segs:
            if i not in tm and i not in seen:
                seen.add(i)
                out.append((i, t))
    return out


# ------------------------------------------------------------------ writing a language file
def localize_text(slug, code, tm):
    meta, d, plan, segs = article_plan(slug)
    hl = CODE2HL[code]
    missing = [i for i, _ in segs if i not in tm]
    if missing:
        return None, missing

    def P(x):
        i, t = x
        return tm[i] if i else t

    def H(text):
        return frag_render(text, lambda s: tm[s.id] if s.id else s.text)

    sec = UI[hl]["cats"][meta["cat"]] if plan["section"] is None else P(plan["section"])
    out = [GEN % code]
    out += ["== title ==", P(plan["title"]), "== seo_title ==", P(plan["seo_title"]) + (SEO_SUFFIX if plan["seo_suffix"] else ""),
            "== desc ==", P(plan["desc"]), "== dek ==", P(plan["dek"]), "== section ==", sec,
            "== tags ==", " | ".join(P(t) for t in plan["tags"]), "== keywords ==", P(plan["keywords"]), "== read ==", d["read"],
            "== q ==", P(plan["q"]), "== a ==", P(plan["a"]), "== takeaways =="]
    out += ["- " + H(x) for x in plan["takeaways"]]
    if plan["alt"][1]:
        out += ["== alt ==", P(plan["alt"])]
    out += ["== body ==", H(plan["body"]), "== insight_quote ==", P(plan["insight_quote"]), "== insight ==", P(plan["insight"]),
            "== prop_eyebrow ==", d.get("prop_eyebrow", "GEO Autopilot · Social Autopilot · Ads"),
            "== prop_intro ==", H(plan["prop_intro"]), "== prop_items =="]
    out += ["- " + H(x) for x in plan["prop_items"]]
    out += ["== prop_outro ==", H(plan["prop_outro"]), "== faq =="]
    for q, a in plan["faq"]:
        out += ["Q: " + P(q), "A: " + H(a)]
    out += ["== note ==", P(plan["note"])]
    return "\n".join(out) + "\n", []


def cmd_write(codes):
    import shutil
    from articles import url_for  # noqa: E402
    total = {}
    for code in codes:
        hl = CODE2HL[code]
        tm = load_tm(code)
        n = 0
        for slug in slugs():
            if is_original(slug, hl):
                continue
            p = os.path.join(ART, slug, hl + ".txt")
            txt, missing = localize_text(slug, code, tm)
            if txt is None:
                if os.path.exists(p):   # English changed since it was published: take the page down until re-translated
                    os.remove(p)
                    page = os.path.join(ROOT, url_for(slug, hl, load_meta(slug)).strip("/"))
                    if os.path.isdir(page):
                        shutil.rmtree(page)
                    print("withdrawn (incomplete again):", code, slug, len(missing), "segments missing")
                continue
            old = open(p, encoding="utf-8").read() if os.path.exists(p) else None
            if old != txt:
                with open(p, "w", encoding="utf-8") as f:
                    f.write(txt)
            n += 1
        total[code] = n
        print("%-8s %d articles written" % (code, n))
    return total


# ------------------------------------------------------------------ commands
def check_ph(en, tr):
    return sorted(PH_RE.findall(en)) == sorted(PH_RE.findall(tr))


def cmd_merge(code, f):
    src = write_source(all_plans())
    tm = load_tm(code)
    bad = n = 0
    for ln in open(f, encoding="utf-8").read().splitlines():
        if not ln.strip() or "\t" not in ln:
            continue
        i, t = ln.split("\t", 1)
        i, t = i.strip(), t.strip()
        if i not in src:
            print("unknown id", i)
            bad += 1
            continue
        if not t:
            print("empty", i)
            bad += 1
            continue
        if not check_ph(src[i], t):
            print("placeholder mismatch", i, src[i][:60], "||", t[:60])
            bad += 1
            continue
        tm[i] = t
        n += 1
    save_tm(code, tm)
    print("merged %d, rejected %d -> i18n/articles_tm/%s.json (%d entries)" % (n, bad, code, len(tm)))
    return bad


def cmd_export(codes, out_dir):
    plans = all_plans()
    write_source(plans)
    os.makedirs(out_dir, exist_ok=True)
    for code in codes:
        lines = todo_lines(code, plans)
        p = os.path.join(out_dir, code + ".todo.tsv")
        if lines:
            with open(p, "w", encoding="utf-8") as f:
                for i, t in lines:
                    f.write("%s\t%s\n" % (i, t.replace("\t", " ").replace("\n", " ")))
        elif os.path.exists(p):
            os.remove(p)
        words = sum(len(PH_RE.sub(" ", t).split()) for _, t in lines)
        print("%-8s %5d segments %7d words -> %s" % (code, len(lines), words, p if lines else "(complete)"))


def cmd_status():
    plans = all_plans()
    print("%-8s %9s %15s" % ("lang", "articles", "segments"))
    for hl in NEW_LANGS:
        code = L[hl]["code"]
        tm = load_tm(code)
        need = needed(code, plans)
        ids = {i for p in need for i, _ in p[4]}
        done = sum(1 for p in need if all(i in tm for i, _ in p[4]))
        orig = len(plans) - len(need)
        print("%-8s %4d/%-4d %7d/%-7d%s" % (code, done, len(need), len(ids & set(tm)), len(ids), ("  (+%d originals)" % orig) if orig else ""))


def main(argv):
    if not argv:
        print(__doc__)
        return 1
    cmd, rest = argv[0], argv[1:]
    all_codes = [L[h]["code"] for h in NEW_LANGS]
    if cmd == "export":
        out = TODO_DIR
        if "--out" in rest:
            k = rest.index("--out")
            out = rest[k + 1]
            rest = rest[:k] + rest[k + 2:]
        cmd_export(rest or all_codes, out)
    elif cmd == "todo":
        for i, t in todo_lines(rest[0], all_plans()):
            print("%s\t%s" % (i, t))
    elif cmd == "merge":
        return 1 if cmd_merge(rest[0], rest[1]) else 0
    elif cmd == "write":
        cmd_write(rest or all_codes)
    elif cmd == "status":
        cmd_status()
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
