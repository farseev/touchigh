SEO_SUFFIX = " | ToucHigh"

INLINE = {"a", "abbr", "b", "br", "code", "em", "i", "mark", "q", "s", "small", "span", "strong", "sub", "sup", "u", "time", "kbd", "wbr"}
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr", "param"}
ATOMIC = {"code", "kbd"}          # kept whole as <xN/>: code samples, robots.txt lines, regexes
SKIP = {"script", "style", "svg", "noscript", "template", "pre"}
ATTRS = ("alt", "title", "aria-label")
KEEP_RE = re.compile(r"^(?:ToucHigh(?: PRO)?|GEO Autopilot|Social Autopilot|Ads Autopilot|SEO/AEO/GEO|SEO|AEO|GEO|ACoS|TACoS|ROAS|CTR|CPC|CPM|"
                     r"[\d\s.,:;+×x–\-−%°~<>=/()·$€£¥]*(?:\s?(?:%|x|k|K|M|B|USD|US\$|RMB|CNY))?[\d\s.,:;+×x–\-−%°~<>=/()·$€£¥]*)$")
PH_RE = re.compile(r"</?g\d+>|<x\d+/>")


def sid(text):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def norm(s):
    return re.sub(r"[ \t\n\r\f\v]+", " ", s).strip(" \t\n\r\f\v")


def translatable(t):
    return bool(t) and bool(re.search(r"[^\W\d_]", t)) and not KEEP_RE.match(t)


def esc_text(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\xa0", "&nbsp;")


# ------------------------------------------------------------------ HTML fragment parsing (from exostride/tools/i18n.py)
class Tok:
    __slots__ = ("kind", "tag", "attrs", "start", "end", "raw", "el")

    def __init__(self, kind, tag, attrs, start):
        self.kind, self.tag, self.attrs, self.start, self.end, self.raw, self.el = kind, tag, attrs, start, None, None, None


class El:
    __slots__ = ("tag", "attrs", "open", "close", "children", "parent")

    def __init__(self, tag, attrs, open_i, parent):
        self.tag, self.attrs, self.open, self.close, self.children, self.parent = tag, dict(attrs), open_i, None, [], parent


class Parser(HTMLParser):
    def __init__(self, doc):
        super().__init__(convert_charrefs=False)
        self.lines = [0] + [m.end() for m in re.finditer("\n", doc)]
        self.toks = []

    def off(self):
        ln, col = self.getpos()
        return self.lines[ln - 1] + col

    def add(self, kind, tag=None, attrs=()):
        self.toks.append(Tok(kind, tag, attrs, self.off()))

    def handle_starttag(self, tag, attrs): self.add("start", tag, attrs)
    def handle_startendtag(self, tag, attrs): self.add("startend", tag, attrs)
    def handle_endtag(self, tag): self.add("end", tag)
    def handle_data(self, d): self.add("data")
    def handle_entityref(self, n): self.add("data")
    def handle_charref(self, n): self.add("data")
    def handle_comment(self, d): self.add("other")
    def handle_decl(self, d): self.add("other")
    def handle_pi(self, d): self.add("other")
    def unknown_decl(self, d): self.add("other")


def parse_html(doc):
    p = Parser(doc)
    p.feed(doc)
    p.close()
    toks = p.toks
    for i, t in enumerate(toks):
        t.end = toks[i + 1].start if i + 1 < len(toks) else len(doc)
        t.raw = doc[t.start:t.end]
    root = El("#root", (), -1, None)
    cur = root
    for i, t in enumerate(toks):
        if t.kind in ("start", "startend"):
            el = El(t.tag, t.attrs, i, cur)
            t.el = el
            cur.children.append(("el", el))
            if t.kind == "start" and t.tag not in VOID:
                cur = el
            else:
                el.close = i
        elif t.kind == "end":
            x = cur
            while x is not root and x.tag != t.tag:
                x = x.parent
            if x is not root:
                x.close = i
                cur = x.parent
        elif t.kind == "data":
            cur.children.append(("tok", i))
    return toks, root


class Seg:
    __slots__ = ("kind", "text", "id", "a", "b", "tags", "lead", "trail", "tok", "attr")


def _ser(toks, children, tagmap):
    out = []

    def ser(kind, x):
        if kind == "tok":
            out.append(html.unescape(toks[x].raw))
            return
        n = len(tagmap) + 1
        if x.close is None or x.close == x.open or x.tag in VOID or x.tag in ATOMIC:
            tagmap.append(("x", x.open, x.close))
            out.append("<x%d/>" % n)
        else:
            tagmap.append(("g", x.open, x.close))
            out.append("<g%d>" % n)
            for c in x.children:
                ser(*c)
            out.append("</g%d>" % n)
    for c in children:
        ser(*c)
    return "".join(out)


def frag_segments(doc):
    """Segments of an HTML fragment: text runs (with placeholders) and alt/title/aria-label attributes."""
    toks, root = parse_html(doc)
    segs = []

    def is_inline(c):
        return c[0] == "tok" or c[1].tag in INLINE

    def first_tok(c):
        return c[1] if c[0] == "tok" else c[1].open

    def last_tok(c):
        return c[1] if c[0] == "tok" else (c[1].close if c[1].close is not None else c[1].open)

    def make(r):
        while r and r[0][0] == "tok" and not toks[r[0][1]].raw.strip():
            r = r[1:]
        while r and r[-1][0] == "tok" and not toks[r[-1][1]].raw.strip():
            r = r[:-1]
        if not r:
            return
        tagmap = []
        t = norm(_ser(toks, r, tagmap))
        a, b = toks[first_tok(r[0])].start, toks[last_tok(r[-1])].end
        s = Seg()
        s.kind, s.a, s.b, s.tags, s.tok, s.attr = "run", a, b, tagmap, None, None
        s.lead = re.match(r"\s*", doc[a:b]).group(0)
        s.trail = re.search(r"\s*$", doc[a:b]).group(0)
        s.text = t
        s.id = sid(t) if translatable(PH_RE.sub("", t)) else None
        segs.append(s)

    def visit(el):
        if el.tag in SKIP or el.attrs.get("translate") == "no":
            return
        runs, run = [], []
        for c in el.children:
            if is_inline(c):
                run.append(c)
            else:
                if run:
                    runs.append(("run", run))
                    run = []
                runs.append(("blk", c))
        if run:
            runs.append(("run", run))
        for kind, r in runs:
            if kind == "blk":
                visit(r[1])
            elif any(k == "tok" and toks[x].raw.strip() for k, x in r):
                make(r)
            else:
                for k, x in r:
                    if k == "el":
                        visit(x)

    visit(root)
    for i, t in enumerate(toks):
        if t.kind not in ("start", "startend"):
            continue
        at = dict(t.attrs)
        for a in ATTRS:
            if at.get(a):
                s = Seg()
                s.kind, s.tok, s.attr, s.tags, s.lead, s.trail, s.a, s.b = "attr", i, a, [], "", "", None, None
                s.text = norm(at[a])
                s.id = sid(s.text) if translatable(s.text) else None
                segs.append(s)
    return toks, segs


def rebuild_tag(raw, new_attrs):
    for name, val in new_attrs.items():
        raw, _ = re.compile(r'(\s%s=")([^"]*)(")' % re.escape(name)).subn(lambda m: m.group(1) + val + m.group(3), raw, count=1)
    return raw


def frag_render(doc, tr):
    """Re-render an HTML fragment with tr(seg) -> text for every segment."""
    toks, segs = frag_segments(doc)
    newtag = {}
    for s in segs:
        if s.kind == "attr":
            newtag[s.tok] = rebuild_tag(newtag.get(s.tok, toks[s.tok].raw), {s.attr: html.escape(tr(s), quote=True)})
    edits, covered = [], []
    for s in segs:
        if s.kind != "run":
            continue
        txt = tr(s)
        pieces, pos = [], 0
        for m in PH_RE.finditer(txt):
            pieces.append(esc_text(txt[pos:m.start()]))
            ph = m.group(0)
            kind, o, c = s.tags[int(re.search(r"\d+", ph).group(0)) - 1]
            if kind == "x":
                if c is not None and c != o:      # atomic element: copied whole
                    pieces.append(doc[toks[o].start:toks[c].end])
                else:
                    pieces.append(newtag.get(o, toks[o].raw))
            elif ph.startswith("</"):
                pieces.append(toks[c].raw)
            else:
                pieces.append(newtag.get(o, toks[o].raw))
            pos = m.end()
        pieces.append(esc_text(txt[pos:]))
        edits.append((s.a, s.b, s.lead + "".join(pieces) + s.trail))
        covered.append((s.a, s.b))
    for i, raw in newtag.items():
        t = toks[i]
        if not any(a <= t.start < b for a, b in covered):
            edits.append((t.start, t.end, raw))
    edits.sort(key=lambda e: e[0])
    res, pos = [], 0
    for a, b, txt in edits:
        res.append(doc[pos:a])
        res.append(txt)
        pos = b
    res.append(doc[pos:])
    return "".join(res)


