#!/usr/bin/env python3
"""Segmented translation path for blog articles (stdlib only).

Source = the English version of every article, i18n/articles/<slug>/en.txt. Each translatable piece
(title, SEO title, meta description, dek, the question and short answer, takeaways, hero alt text,
every paragraph / heading / list item / table cell of the body, the insight, the "How ToucHigh helps"
box, FAQ questions and answers, the note, tags and keywords) is a *segment*, keyed by a hash of its
English text (sha1[:10], the same scheme as tools/localize.py). Inline markup inside a segment is shown
as <g1>…</g1> (paired tags such as <strong>, <a>) and <x1/> (void or atomic tags such as <br>, <code>);
translators keep the placeholders and the tags are restored from the English.

Translations live in i18n/articles_tm/<code>.json ({id: text}); i18n/articles_tm/source.json holds
the English of every current segment. An article is written in a language (i18n/articles/<slug>/<hl>.txt,
then rendered by tools/articles.py at /blog/<code>/<slug>/) only when 100 % of its segments are translated.
Files written here start with a "# generated" line; hand-written originals (no such line) are never touched.

  python3 tools/article_i18n.py export [codes] [--out DIR]   write DIR/<code>.todo.tsv (id<TAB>English)
  python3 tools/article_i18n.py todo <code>                  print untranslated segments
  python3 tools/article_i18n.py merge <code> <file.tsv>      merge id<TAB>translation lines (checked)
  python3 tools/article_i18n.py write [codes]                write <hl>.txt for 100 %-translated articles
  python3 tools/article_i18n.py status                       articles / segments translated per language
"""
